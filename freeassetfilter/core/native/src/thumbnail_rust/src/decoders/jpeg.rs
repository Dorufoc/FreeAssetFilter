//! JPEG 解码器（todo 15 实现）。
//!
//! Design Revision 5 落地：**不自研 JPEG 解码**（Huffman/IDCT/渐进谱等），接线 image
//! crate 内建覆盖——`image` 的 `jpeg` feature 启用后解码后端为 **zune-jpeg 0.5.15**
//! （纯 Rust，todo 2/3 选型实证），基线（SOF0）+ 渐进（SOF2）、4:4:4/4:2:2/4:2:0、
//! 重启标记、EXIF/APPn 跳过等全由 image crate 承担。
//!
//! 本模块只做**接线 + 防御性上限**（image crate 内建解码器不设 `Limits`，解压
//! 炸弹防御由本模块 marker 预检自担）：
//! - 预检 A：SOI 魔数（`FF D8`）校验，空输入/垃圾/非 JPEG 头直接
//!   `STATUS_DECODE_FAILED=-2`。
//! - 预检 B：`scan_sof_dimensions` 扫描 marker 序列定位 SOF0/SOF1/SOF2
//!   （`FFC0/FFC1/FFC2`）读取 height/width，超限（`w*h > 8192×8192`）在
//!   **解码前**返回 `STATUS_TOO_LARGE=-7`（伪造 SOF 的解压炸弹不触发 image
//!   大分配）；上限与 `thumbnail_manager.py` MAX_IMAGE_DIMENSION 及 todo 34
//!   `infra/limits` 对齐。
//! - 维度放行后委托 `image::load_from_memory` 完整解码（EXIF/APPn 跳过、
//!   4:4:4/4:2:2/4:2:0、灰阶、渐进 SOF2 全由 image crate 内建 zune-jpeg 承担）
//!   → `to_rgba8()` → `into_raw()`；任何解码 Err → `STATUS_DECODE_FAILED=-2`。
//! - 供视频路径复用：todo 24 会把 ffmpeg MJPEG 输出的解码从 legacy
//!   `decode_image_bytes_to_rgba` 切到本函数（视频帧本是 JPEG 流）。

use crate::{STATUS_DECODE_FAILED, STATUS_TOO_LARGE};

/// 解码尺寸上限（像素）。与 `thumbnail_manager.py:216-217` MAX_IMAGE_DIMENSION=8192
/// 及 todo 34 `infra/limits.rs::check_dimensions` 对齐；todo 34 落地前本常量先行。
const MAX_JPEG_DIM: u32 = 8192;

/// 像素数上限 `8192*8192`（u64 固定值，避免 u32 乘法溢出）。
const MAX_PIXELS: u64 = MAX_JPEG_DIM as u64 * MAX_JPEG_DIM as u64;

/// JPEG SOI 魔数 `FF D8`。
const SOI_MARKER: [u8; 2] = [0xFF, 0xD8];

#[allow(dead_code)]
// 该函数供 todo 16/17/20/24（由 legacy decode_image_bytes_to_rgba 切换）接线；
// 当前 crate 为 cdylib 且尚未有解码器引入，仅 `#[cfg(test)]` 引用到它，故显式标注
// 以避免 dead_code 警告（同 infra/resize.rs 先例）。
/// 从内存字节解码 JPEG 为 RGBA8（不缩放）。
///
/// # 参数
/// - `bytes`：完整 JPEG 文件字节（也可为 ffmpeg `-f image2pipe` 输出的 MJPEG 帧）。
///
/// # 返回
/// - `Ok((Vec<u8>, width, height))`：RGBA8 像素流（行优先，每像素 R,G,B,A）。
/// - `Err(STATUS_DECODE_FAILED=-2)`：解码失败/损坏/截断/非 JPEG 输入。
/// - `Err(STATUS_TOO_LARGE=-7)`：解码尺寸超过 8192×8192（解码前拦截，不分配巨量内存）。
///
/// # 错误不变量
/// 任何输入（含空切片、任意截断、伪造头）都不会 panic，只会返回结果或错误码。
pub fn decode_jpeg(bytes: &[u8]) -> Result<(Vec<u8>, u32, u32), i32> {
    // 预检 A：SOI 魔数（`FF D8`）。空输入 / 垃圾 / 非 JPEG 头 → -2。
    if bytes.len() < 2 || &bytes[0..2] != SOI_MARKER {
        return Err(STATUS_DECODE_FAILED);
    }
    // 预检 A'：EOI 尾标记（`FF D9`）。JPEG 规范 EOI 为必备尾部标记；image crate
    // 的 zune-jpeg 对仅截掉尾部（丢失 EOI）的输入宽容解码成功，若此截断不被拦截，
    // 测试契约「截断输入必须返回错误」将被打破。PIL/ffmpeg 产出的合法 JPEG 与
    // MJPEG 帧均以 `FF D9` 结尾，此检查不误伤合法输入 → 截断统一 -2。
    if !bytes.ends_with(&[0xFF, 0xD9]) {
        return Err(STATUS_DECODE_FAILED);
    }
    // 预检 B：扫描 SOF 段宽高做解压炸弹防御——超限声明（如伪造 SOF 10000×10000）
    // 在进入 image crate 分配像素缓冲之前返回 -7。扫描失败（无 SOF / 头截断 /
    // 结构损坏）不下结论，交 image crate 判定（正常流 SOF0/1/2 必在 SOS 前出现，
    // 扫不到即输入损坏，image 终归返回 -2）。
    if let Ok((w, h)) = scan_sof_dimensions(bytes) {
        if is_oversized(w, h) {
            return Err(STATUS_TOO_LARGE);
        }
    }
    // 委托 image crate 内建解码（Design Revision 5：不自研 IDCT/Huffman）。
    // EXIF/APPn 段跳过、4:4:4/4:2:2/4:2:0、灰阶、渐进（SOF2）由 zune-jpeg
    // 全权承担；`to_rgba8` 统一 RGBA8 输出契约。
    let rgba = image::load_from_memory(bytes)
        .map_err(|_| STATUS_DECODE_FAILED)?
        .to_rgba8();
    let w = rgba.width();
    let h = rgba.height();
    Ok((rgba.into_raw(), w, h))
}

/// 扫描 JPEG marker 序列并读取 SOF0/SOF1/SOF2（`FFC0`/`FFC1`/`FFC2`）段的
/// `(width, height)`（均 u16 大端）。
///
/// 逐 marker 前进：`FF XX` 后跟 2 字节大端段长度（含长度自身 2 字节）跳过整段；
/// APPn / COM / DHT / DQT / DRI 等全部跳过；遇 SOS（`FFDA`，其后是熵编码数据、
/// 不会再出现 SOF）或无 SOF 即返回 `Err(STATUS_DECODE_FAILED)`。所有边界比较
/// 基于 `bytes.len()`，越界返回 `Err(STATUS_DECODE_FAILED)`，不 panic。
fn scan_sof_dimensions(bytes: &[u8]) -> Result<(u32, u32), i32> {
    // 越过 SOI（decode_jpeg 已校验 `FF D8`）。
    let mut pos: usize = 2;
    while pos + 1 < bytes.len() {
        if bytes[pos] != 0xFF {
            // 段间 0xFF 填充已在下一分支处理；此处出现非 FF 属结构损坏。
            return Err(STATUS_DECODE_FAILED);
        }
        let marker: u8 = bytes[pos + 1];
        if marker == 0xFF {
            // 连续填充字节（如 0xFF 0xFF 对），前进一位。
            pos += 1;
            continue;
        }
        if marker == 0xDA {
            // SOS：其后为熵编码数据，SOF 不会再出现 → 无 SOF 判定失败。
            return Err(STATUS_DECODE_FAILED);
        }
        if matches!(marker, 0xC0 | 0xC1 | 0xC2) {
            // SOF 段布局：len(2B)+precision(1B)+height(2B)+width(2B)，i 指向
            // len 字段起始（marker 之后 2 字节）：height 在 i+3..i+5、width
            // 在 i+5..i+7。
            if pos + 9 > bytes.len() {
                return Err(STATUS_DECODE_FAILED);
            }
            let i: usize = pos + 2;
            let h: u32 = u32::from(u16::from_be_bytes([bytes[i + 3], bytes[i + 4]]));
            let w: u32 = u32::from(u16::from_be_bytes([bytes[i + 5], bytes[i + 6]]));
            return Ok((w, h));
        }
        // 无段长度的独立标记（TEM `01` / RSTn `D0-D7` / SOI `D8` / EOI `D9`）：
        // 正常流中 SOS 前只可能出现 TEM，余者防御性跳过。
        let standalone: bool = matches!(marker, 0x01 | 0xD0..=0xD9);
        if standalone {
            pos += 2;
            continue;
        }
        // 带长度字段的段：读 2 字节大端长度（含长度自身）。
        if pos + 4 > bytes.len() {
            return Err(STATUS_DECODE_FAILED);
        }
        let seg_len: usize = usize::from(u16::from_be_bytes([bytes[pos + 2], bytes[pos + 3]]));
        if seg_len < 2 || pos + 2 + seg_len > bytes.len() {
            return Err(STATUS_DECODE_FAILED);
        }
        pos += 2 + seg_len;
    }
    Err(STATUS_DECODE_FAILED)
}

/// `w*h > 8192*8192` 判定（u64 乘法，避免 u32 溢出）。
fn is_oversized(w: u32, h: u32) -> bool {
    u64::from(w) * u64::from(h) > MAX_PIXELS
}

