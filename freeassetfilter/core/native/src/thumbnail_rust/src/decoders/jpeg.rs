    /// 读取 RGBA 像素（测试辅助）。
    fn pixel(data: &[u8], w: u32, x: u32, y: u32) -> [u8; 4] {
        let i = ((y * w + x) as usize) * 4;
        [data[i], data[i + 1], data[i + 2], data[i + 3]]
    }

    /// 仅校验"解码成功 + 16x16 RGBA8 + 不透明 + 内容非空"的通用契约。
    fn assert_16x16_rgba(result: Result<(Vec<u8>, u32, u32), i32>, fixture: &str) {
        let (data, w, h) = result.unwrap_or_else(|e| panic!("{fixture} 应解码成功, got Err({e})"));
        assert_eq!((w, h), (16, 16), "{fixture} 尺寸应为 16x16");
        assert_eq!(data.len(), 16 * 16 * 4, "{fixture} RGBA 字节数应为 16*16*4");
        assert!(
            data.chunks_exact(4).all(|px| px[3] == 255),
            "{fixture} 不透明（alpha=255）"
        );
        assert!(
            data.iter().any(|&b| b != data[0]),
            "{fixture} 内容不应全同（渐变+棋盘内容解码后应有差异）"
        );
    }

    #[test]
    fn baseline_444_q90_decodes_to_16x16_rgba() {
        assert_16x16_rgba(decode_jpeg(JPEG_444_Q90), "JPEG_444_Q90");
        // 4:4:4 无色度下采样：内容渐变沿 x 轴，抽样两点亮度差显著。
        let (data, w, _) = decode_jpeg(JPEG_444_Q90).expect("4:4:4 应解码");
        let p0 = pixel(&data, w, 2, 2);
        let p1 = pixel(&data, w, 11, 11);
        assert!(
            (i16::from(p1[0]) - i16::from(p0[0])).abs() > 100,
            "4:4:4 渐变内容：p0={p0:?} p1={p1:?} 亮度差异应 >100"
        );
    }

