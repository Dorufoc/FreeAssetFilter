    /// 计算两段 RGBA8 逐通道绝对差的最大值（acceptance「与 libwebp 像素差值
    /// ≤3/255」的判定函数；两输入等长，差值经 u32 绝对值化无溢出）。
    fn max_channel_diff(a: &[u8], b: &[u8]) -> u32 {
        assert_eq!(a.len(), b.len(), "RGBA 长度不一致");
        a.iter()
            .zip(b.iter())
            .map(|(&x, &y)| (i32::from(x) - i32::from(y)).unsigned_abs())
            .max()
            .unwrap_or(0)
    }

