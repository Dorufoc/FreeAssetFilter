    #[test]
    fn vp8_dimensions_parses_header() {
        assert_eq!(vp8_dimensions(VP8_FLAT_GRAY_Q50_16X16), Ok((16, 16)));
        assert_eq!(vp8_dimensions(VP8_WIDE_GRADIENT_Q80_24X16), Ok((24, 16)));
        // LE 布局：字节 6-7 / 8-9 小端 u16 + 0x3FFF 掩码（300x200 实测样例）。
        assert_eq!(
            vp8_dimensions(&[0x00, 0x00, 0x00, 0x9d, 0x01, 0x2a, 0x2c, 0x01, 0xc8, 0x00, 0x00]),
            Ok((300, 200))
        );
        // 头不足 / 非关键帧 / 坏起始码 / 零尺寸各拒绝一次。
        assert_eq!(vp8_dimensions(&[0x00; 9]), Err(STATUS_DECODE_FAILED), "头不足");
        assert_eq!(
            vp8_dimensions(&[0x01, 0x00, 0x00, 0x9d, 0x01, 0x2a, 0x10, 0x00, 0x10, 0x00]),
            Err(STATUS_DECODE_FAILED),
            "非关键帧"
        );
        assert_eq!(
            vp8_dimensions(&[0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x10, 0x00]),
            Err(STATUS_DECODE_FAILED),
            "坏起始码"
        );
        assert_eq!(
            vp8_dimensions(&[0x00, 0x00, 0x00, 0x9d, 0x01, 0x2a, 0x00, 0x00, 0x10, 0x00]),
            Err(STATUS_DECODE_FAILED),
            "零宽"
        );
    }

