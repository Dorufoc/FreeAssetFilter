    // ---- 验收：非关键帧 / 损坏 / 超限返回错误不 panic ----------------------

    #[test]
    fn non_keyframe_interframe_returns_error_without_panic() {
        // 帧标记 bit0=1（interframe）：依赖参考帧，无法独立解码 → -2。
        // 合法关键帧夹具仅翻转帧类型位。
        let mut frame = VP8_FLAT_GRAY_Q50_16X16.to_vec();
        frame[0] |= 0x01;
        assert_eq!(
            decode_vp8(&frame),
            Err(STATUS_DECODE_FAILED),
            "非关键帧应返回 -2"
        );
        // 显式构造的最小 interframe 头同样拒绝。
        assert_eq!(
            decode_vp8(&[0x01, 0x00, 0x00, 0x9d, 0x01, 0x2a, 0x10, 0x00, 0x10, 0x00, 0x00]),
            Err(STATUS_DECODE_FAILED)
        );
    }

    #[test]
    fn oversize_declared_dimensions_return_status_too_large() {
        // 伪造关键帧头声明 10000x10000（LE 14-bit）：像素数 1e8 > 8192² → -7，
        // 解码前拦截，不交给 image 分配内存。
        let mut hdr = vec![0x00, 0x00, 0x00, 0x9d, 0x01, 0x2a];
        hdr.extend_from_slice(&10000u16.to_le_bytes()); // 宽
        hdr.extend_from_slice(&10000u16.to_le_bytes()); // 高
        hdr.extend_from_slice(&[0x00; 8]); // 后续码流任意占位
        assert_eq!(
            decode_vp8(&hdr),
            Err(STATUS_TOO_LARGE),
            "10000x10000 应返回 -7 而非解码成功/崩溃"
        );
    }

    #[test]
    fn corrupt_and_truncated_return_error_without_panic() {
        // 空输入 / 非 VP8 字节 / 头不足 10 字节。
        assert_eq!(decode_vp8(b""), Err(STATUS_DECODE_FAILED), "空输入应返回 -2");
        assert_eq!(
            decode_vp8(b"garbage not vp8"),
            Err(STATUS_DECODE_FAILED),
            "非 VP8 字节应返回 -2"
        );
        assert_eq!(
            decode_vp8(&[0x00, 0x00, 0x00, 0x9d]),
            Err(STATUS_DECODE_FAILED),
            "头不足应返回 -2"
        );
        // 起始码损坏：翻转起始码字节（预检拦截）。
        let mut bad_code = VP8_FLAT_GRAY_Q50_16X16.to_vec();
        bad_code[4] ^= 0xFF;
        assert_eq!(
            decode_vp8(&bad_code),
            Err(STATUS_DECODE_FAILED),
            "坏起始码应返回 -2"
        );
        // 截断：完整 10 字节头 + 部分码流（预检通过，image-webp 解码失败 → -2）。
        // flat_gray payload 共 24 字节，取 [..20] 保持头完整并截断尾部码流。
        let truncated = &VP8_FLAT_GRAY_Q50_16X16[..20];
        assert_eq!(
            decode_vp8(truncated),
            Err(STATUS_DECODE_FAILED),
            "截断码流应返回 -2"
        );
    }

