//! VP8 有损解码器（todo 19 实现；Design Revision 5 落地）。
//!
//! 职责：**不自研 RFC 6386**——VP8 有损帧本质是 WebP 容器的 `VP8 ` chunk 负载，
//! image crate `webp` feature 的 image-webp v0.2.4（纯 Rust）内建 VP8 有损解码
//! （bool 算术编码器、帧内预测 DC/V/H/TM/B_PRED、逆 DCT/WHT、环路滤波全含）。
//! 本模块唯一逻辑：① 帧头防御预检（关键帧判定、宽高上限 -7、非关键帧/损坏
//! 返回错误不 panic）；② 把裸 VP8 帧包成最小 RIFF/WEBP 容器（纯胶水）转发
//! `image::load_from_memory` → `to_rgba8`。
//!
//! 说明：raw `.vp8` 文件（无容器）与 WebP 内 `VP8 ` chunk 的负载是同一码流，
//! 本入口直接接收负载字节，两种来源等价。VP8 有损仅用于 WebP 容器内有损块；
//! 视频缩略图走 ffmpeg T2，不经过此解码器。
//!
//! 输出统一 RGBA8（4 字节/像素），与其余 T1 解码器契约一致：
//! `Result<(Vec<u8>, u32, u32), i32>`。

use crate::{STATUS_DECODE_FAILED, STATUS_TOO_LARGE};

/// 防御性上限：目标解码尺寸 ≤ 8192×8192，与 `thumbnail_manager.py`
/// MAX_IMAGE_DIMENSION 对齐（防解压炸弹）。
///
/// 后续 todo 34 会统一接入 `infra/limits.rs::check_dimensions`，届时本常量
/// 及其校验点迁移至统一的 `check_dimensions(w, h)` 入口。
const MAX_IMAGE_DIMENSION: u32 = 8 * 1024;

/// 像素数上限 `8192*8192`（u64 常量，避免 u32 乘法溢出）。
const MAX_PIXELS: u64 = 8_192 * 8_192;

/// VP8 帧头固定长度：3 字节帧标记 + 3 字节起始码 + 2 字节宽 + 2 字节高。
const VP8_HEADER_LEN: usize = 10;

/// 关键帧起始码（RFC 6386 §9.2；libwebp 与 image-webp 同一魔数）。
const VP8_START_CODE: [u8; 3] = [0x9D, 0x01, 0x2A];

/// 解析 VP8 帧头并做防御预检，返回 `(宽, 高)`。
///
/// 帧头布局（RFC 6386 §9.1/§9.2，offset 0 起）：
/// - 字节 0 bit0：帧类型（0=关键帧，1=非关键帧，依赖参考帧）
/// - 字节 3-5：关键帧起始码 `0x9D 0x01 0x2A`
/// - 字节 6-7：宽（14-bit 小端 u16，高 2 bit 为水平缩放位）
/// - 字节 8-9：高（同上）
///
/// 错误语义：头不足 / 非关键帧 / 起始码错 / 零尺寸 → `STATUS_DECODE_FAILED(-2)`；
/// 超限判定由调用方用返回值对 `MAX_PIXELS` 检查（返回 `-7`）。
fn vp8_dimensions(bytes: &[u8]) -> Result<(u32, u32), i32> {
    if bytes.len() < VP8_HEADER_LEN {
        return Err(STATUS_DECODE_FAILED);
    }
    // 非关键帧（interframe）依赖参考帧，无法独立解码。任务原文允许 -2/-6 二选一；
    // 取 -2（STATUS_DECODE_FAILED）：-6（STATUS_UNSUPPORTED）按 decisions.md 仅由
    // T3 跳过/未注册格式返回，解码器内混用会污染 todo 27 的路由语义。
    if bytes[0] & 1 != 0 {
        return Err(STATUS_DECODE_FAILED);
    }
    if bytes[3..6] != VP8_START_CODE {
        return Err(STATUS_DECODE_FAILED);
    }
    // 尺寸为 14-bit 小端 u16，按 0x3FFF 掩码取低 14 bit。此布局经 libwebp 实测
    // 确认：PIL 300x200 有损 webp 帧头字节 6-9 为 `2c 01 c8 00`（LE=300/200），
    // image-webp decoder.rs:395-399 读法一致（`read_u16::<LittleEndian> & 0x3FFF`）。
    let w = u32::from(u16::from_le_bytes([bytes[6], bytes[7]]) & 0x3FFF);
    let h = u32::from(u16::from_le_bytes([bytes[8], bytes[9]]) & 0x3FFF);
    if w == 0 || h == 0 {
        return Err(STATUS_DECODE_FAILED);
    }
    Ok((w, h))
}

/// 像素数是否超限（u64 乘法，避免 u32 溢出）。
fn is_oversized(w: u32, h: u32) -> bool {
    u64::from(w) * u64::from(h) > MAX_PIXELS
}

#[allow(dead_code)]
// 解码器未接线 lib.rs（待 todo 24/26 经 infra/registry 分发接入）；cdylib 构建下
// 当前仅 `#[cfg(test)]` 引用，显式标注避免 dead_code 警告（同 decoders/pnm.rs
// 的 decode_pnm 先例）。
/// 解码 VP8 有损帧为 RGBA8（`Vec<u8>` 行优先、每像素 4 字节）。
///
/// 输入为 WebP 容器内 `VP8 ` chunk 的负载（或裸 `.vp8` 文件字节，同一码流）。
/// 实现 = 帧头防御预检 + 最小 RIFF/WEBP 容器胶水 + `image::load_from_memory`。
///
/// # 错误语义
/// - 尺寸超限（帧头声明像素数 > 8192×8192）→ `STATUS_TOO_LARGE=-7`（解码前拦截）。
/// - 非关键帧 / 损坏 / 截断 / 头不足 / 非 VP8 → `STATUS_DECODE_FAILED=-2`。
pub fn decode_vp8(bytes: &[u8]) -> Result<(Vec<u8>, u32, u32), i32> {
    // 解压炸弹防御：先解析帧头宽高，超限直接拒绝，不交给 image 分配内存。
    let (w, h) = vp8_dimensions(bytes)?;
    if is_oversized(w, h) {
        return Err(STATUS_TOO_LARGE);
    }

    // 最小 RIFF/WEBP 容器胶水（纯字节拼接，无解码逻辑）：
    //   `RIFF <u32le riff_size> WEBP VP8␣ <u32le chunk_size> <payload>`
    // 容器头共 20 字节；riff_size = 4("WEBP") + 8("VP8␣" 块头) + payload_len =
    // 12 + payload_len（RIFF 规范 file_size - 8）。payload 原样置入，奇数长度无需
    // 偶数填充——image-webp 按 chunk_size 精确取用且其后无后续块（decoder.rs
    // read_chunk_header 的 `chunk_size_rounded` 仅用于跳过后续块定位）。
    let payload_len = bytes.len() as u32;
    let mut container = Vec::with_capacity(20 + bytes.len());
    container.extend_from_slice(b"RIFF");
    container.extend_from_slice(&(12 + payload_len).to_le_bytes());
    container.extend_from_slice(b"WEBP");
    container.extend_from_slice(b"VP8 ");
    container.extend_from_slice(&payload_len.to_le_bytes());
    container.extend_from_slice(bytes);

    // image-webp（经 image crate webp feature）内建解码；截断/损坏在 load 时报错。
    let rgba = image::load_from_memory(&container)
        .map_err(|_| STATUS_DECODE_FAILED)?
        .to_rgba8();
    let (ow, oh) = (rgba.width(), rgba.height());
    Ok((rgba.into_raw(), ow, oh))
}

