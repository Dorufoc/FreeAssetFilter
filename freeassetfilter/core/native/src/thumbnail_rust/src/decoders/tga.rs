    /// RLE 压缩（type=10）：与同源未压缩 TGA 解码结果逐字节一致，且点验包内容。
    #[test]
    fn decodes_rle_truecolor_matches_uncompressed_twin() {
        let (rle, w, h) = decode_tga(TGA_RLE_TRUE_COLOR).expect("RLE TGA 应解码成功");
        let (plain, w2, h2) =
            decode_tga(TGA_RLE_TWIN_UNCOMPRESSED).expect("等效未压缩 TGA 应解码成功");
        assert_eq!((w, h), (5, 4));
        assert_eq!((w2, h2), (5, 4));
        assert_eq!(rle, plain, "RLE 与未压缩等效体应解码出完全一致的像素");
        // 点验 RLE 包语义：行 0 全红（RLE 包 count=5）、行 2 为 5 个异色 raw 包。
        for x in 0..5 {
            assert_eq!(rgba_at(&rle, w, x, 0), [255, 0, 0, 255], "行 0 应全红");
        }
        assert_eq!(rgba_at(&rle, w, 0, 2), [255, 255, 0, 255], "row2 col0 黄");
        assert_eq!(rgba_at(&rle, w, 1, 2), [0, 255, 255, 255], "row2 col1 青");
        assert_eq!(rgba_at(&rle, w, 2, 2), [255, 0, 255, 255], "row2 col2 品红");
        assert_eq!(rgba_at(&rle, w, 3, 2), [255, 255, 255, 255], "row2 col3 白");
        assert_eq!(rgba_at(&rle, w, 4, 2), [0, 0, 0, 255], "row2 col4 黑");
    }

    /// 16bpp 真彩（RGB5x1）：image crate 按 LUT `255*x/31` 展开为 8bit RGB。
    #[test]
    fn decodes_16bpp_truecolor_expands_to_rgb() {
        let (data, w, h) = decode_tga(TGA_16BPP_TRUE_COLOR).expect("16bpp TGA 应解码成功");
        assert_eq!((w, h), (3, 2));
        let expected: &[(u32, u32, [u8; 4])] = &[
            // 源（5-bit RGB）→ LUT 展开 + alpha=255
            (0, 0, [0, 0, 0, 255]),              // (0,0,0)
            (1, 0, [255, 0, 0, 255]),            // (31,0,0)
            (2, 0, [0, 255, 0, 255]),            // (0,31,0)
            (0, 1, [0, 0, 255, 255]),            // (0,0,31)
            (1, 1, [165, 123, 82, 255]),         // (20,15,10)
            (2, 1, [255, 255, 255, 255]),        // (31,31,31)
        ];
        for &(x, y, exp) in expected {
            assert_eq!(rgba_at(&data, w, x, y), exp, "16bpp 像素 ({x},{y})");
        }
    }

    /// 原点方向：desc=0x00（左下）与 desc=0x20（左上）解码结果互为垂直翻转；
    /// 各自动态点验关键行。
    #[test]
    fn origin_bottom_left_and_top_left_are_vertical_flips() {
        let (bottom, w, h) =
            decode_tga(TGA_ORIGIN_BOTTOM_LEFT).expect("左下原点 TGA 应解码成功");
        let (top, _, _) = decode_tga(TGA_ORIGIN_TOP_LEFT).expect("左上原点 TGA 应解码成功");
        assert_eq!((w, h), (3, 3));

        // 左下原点：输出顶行 = 源顶行（red，green，blue）；底行 = gray,(0,0,128),(128,0,0)。
        assert_eq!(rgba_at(&bottom, w, 0, 0), [255, 0, 0, 255]);
        assert_eq!(rgba_at(&bottom, w, 1, 0), [0, 255, 0, 255]);
        assert_eq!(rgba_at(&bottom, w, 2, 0), [0, 0, 255, 255]);
        assert_eq!(rgba_at(&bottom, w, 0, 2), [128, 128, 128, 255]);
        assert_eq!(rgba_at(&bottom, w, 2, 2), [128, 0, 0, 255]);
        // 左上原点：输出顶行 = 源底行；底行 = red,g,B 行（即下原点的顶行）。
        assert_eq!(rgba_at(&top, w, 0, 0), [128, 128, 128, 255]);
        assert_eq!(rgba_at(&top, w, 2, 0), [128, 0, 0, 255]);
        assert_eq!(rgba_at(&top, w, 0, 2), [255, 0, 0, 255]);
        assert_eq!(rgba_at(&top, w, 2, 2), [0, 0, 255, 255]);

        // 垂直翻转等价：top[y] == bottom[H-1-y]，行级比对。
        let row = (w * 4) as usize;
        for y in 0..3 {
            let ty = ((y * w) * 4) as usize;
            let by = (((h - 1 - y) * w) * 4) as usize;
            assert_eq!(&top[ty..ty + row], &bottom[by..by + row], "行 {y} 应互为翻转");
        }
    }

    /// 截断输入：头不足 / 像素数据截断（TGA2 页脚本身可缺省，不能算失败）应返回 -2 而非 panic。
    #[test]
    fn truncated_input_returns_error_without_panic() {
        let full = TGA_24BPP_UNCOMPRESSED;
        // full = 18 字节头 + 8x6x3 像素数据 + 26 字节可选页脚 = 188 字节。
        // 只有切断头或像素数据的字节才应失败；仅切页脚（如 187）仍可解码。
        let pixel_data_end = 18 + 8 * 6 * 3; // 162
        for cut in [0usize, 5, 17, 18, 20, pixel_data_end - 1, pixel_data_end / 2] {
            let result = decode_tga(&full[..cut]);
            assert!(
                matches!(result, Err(STATUS_DECODE_FAILED)),
                "截断到 {cut} 字节应返回 -2，得到 {result:?}"
            );
        }
    }

