    /// 全部有效夹具经本包装解码后与 image crate 直解（基准路径）逐字节一致。
    #[test]
    fn wrapper_matches_raw_image_crate_for_all_fixtures() {
        let fixtures: &[&[u8]] = &[
            TGA_24BPP_UNCOMPRESSED,
            TGA_32BPP_ALPHA,
            TGA_8BPP_PALETTE,
            TGA_RLE_TRUE_COLOR,
            TGA_RLE_TWIN_UNCOMPRESSED,
            TGA_16BPP_TRUE_COLOR,
            TGA_ORIGIN_BOTTOM_LEFT,
            TGA_ORIGIN_TOP_LEFT,
        ];
        for (i, bytes) in fixtures.iter().enumerate() {
            let got = decode_tga(bytes).expect("有效夹具应解码成功");
            // TGA 无魔数，image::load_from_memory 的格式嗅探不支持它
            //（见 image/src/io/free_functions.rs 的 guess_format 文档），
            // 基准路径必须显式指定格式，与包装内部一致。
            let baseline = image::load_from_memory_with_format(bytes, image::ImageFormat::Tga)
                .expect("image crate 直解应成功")
                .to_rgba8();
            assert_eq!(
                got.1,
                baseline.width(),
                "夹具 {i} 宽度应与 image crate 一致"
            );
            assert_eq!(
                got.2,
                baseline.height(),
                "夹具 {i} 高度应与 image crate 一致"
            );
            assert_eq!(
                got.0,
                baseline.into_raw(),
                "夹具 {i} 像素应与 image crate 直解逐字节一致"
            );
        }
    }
