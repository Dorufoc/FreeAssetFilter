//! PSD 解码器（todo 20 实现；依赖 todo 15 jpeg 委托）。
//!
//! 职责：PSD 头 + 颜色模式段 + 图像资源段——**资源 1036（缩略图）优先提取**
//! JPEG/RAW 内嵌预览并解码；无 1036 时尝试扁平 RGB8 合并图层语义（简单模式，
//! 含透明通道）；`8BPS` 魔数 + 位深 8/16；PSB（`version=2`）返回
//! `STATUS_UNSUPPORTED` 交 T3。
//!
//! # 字节序：**全文件大端（BE）**
//!
//! task-20 探针实证（psd-tools 1.18.0 + 本仓库 `task-20-*.py`）：
//! - header 26B：`8BPS` + version(u16) + 保留6B + channels(u16) + height(u32) +
//!   width(u32) + depth(u16) + color_mode(u16) — 全部大端。
//! - 颜色模式段长度 u32、图像资源段长度 u32、Layer/Mask 段长度 u32 — 全部大端
//!   （psd_tools/bin_utils.py `_FORMAT = ">"`；任务 brief「资源段长度字段为 LE」
//!   属**错误**，本地以 psd-tools 源码为准）。
//! - 8BIM 资源块：sig(4) + id(u16 BE) + Pascal 名(1B 长度 + 名称，偶对齐) +
//!   data_len(u32 BE) + data（偶对齐）。
//! - 资源 1036 数据块头部 28B：`6I2H` 全 BE = format(u32), width(u32), height(u32),
//!   widthbytes(u32), totalsize(u32), compsize(u32), bitspixel(u16), planes(u16)；
//!   其后为负载（fmt=1 JPEG 字节 或 fmt=0 交错原始像素）。
//! - ImageData 段：compression(u16 BE) + 平面序像素（R 全平面 → G → B → A，
//!   每平面 w*h*max(1,depth/8) 字节；16 位样本双字节 BE，取高字节即 8 位值）。
//! - PSB（`8BPS` version=2）的 Layer/Mask 段长度字段为 **8 字节**（PSD 规范）——
//!   本解码器对 version=2 直接 `STATUS_UNSUPPORTED`，不进入段解析。
//!
//! # 解码路径（计划 todo 20 Acceptance）
//!
//! 1. 预检 A：长度 ≥26 / 魔数 `8BPS` / `version==2`→`-6`（PSB）、`!=1`→`-2` /
//!   位深 ∉ {8,16}→`-2` / channels==0→`-2`。
//! 2. 预检 B：`w*h > 8192*8192`→`STATUS_TOO_LARGE=-7`（解码前拦截，不分配）。
//! 3. 资源段扫描 1036：命中则按 fmt 解码——fmt=1 JPEG 委托 `jpeg::decode_jpeg`
//!    （SOF 超限由 jpeg 自担 `-7`）；fmt=0 RAW 需 planes==1 且 bits∈{24,32}，
//!    交错缩放 RGBA8（缩略图声明尺寸超限`-7`）；其余 fmt / planes≠1 → `-6`。
//! 4. 无 1036：跳过 Layer/Mask → compression==0（RAW）才可解码（RLE/zip→`-6`）；
//!   仅 color_mode==3（RGB）+ channels∈{3,4}；位深 8/16 平面序 → RGBA8（第 4
//!   平面为 alpha，无则 255）。
//!
//! # 错误不变量
//! 任何输入（含空切片、任意截断、伪造头、越界长度字段）都不会 panic，只会返回
//! 0/±错误码。测试对内嵌夹具 + 截断切片 + 伪造头全覆盖。

use crate::decoders::jpeg::decode_jpeg;
use crate::{STATUS_DECODE_FAILED, STATUS_TOO_LARGE, STATUS_UNSUPPORTED};

/// 解码尺寸上限（像素）。与 `thumbnail_manager.py` MAX_IMAGE_DIMENSION=8192、
/// jpeg.rs/其它解码器及 todo 34 `infra/limits` 对齐。
const MAX_PSD_DIM: u32 = 8192;

/// 像素数上限 `8192*8192`（u64 固定值，避免 u32 乘法溢出）。
const MAX_PIXELS: u64 = 8192 * 8192;

/// PSD 魔数 `8BPS`。
const SIG_8BPS: &[u8; 4] = b"8BPS";

/// 8BIM 资源段签名（仅此签名合法；PSB 的 `8B64` 因 version=2 已在预检 A 拦截）。
const SIG_8BIM: &[u8; 4] = b"8BIM";

/// 缩略图资源 ID（Photoshop 6+）。
const RES_ID_THUMBNAIL: u16 = 1036;

/// 1036 数据块头部固定 28 字节（`6I2H` 全 BE）。
const THUMB_HEADER_LEN: usize = 28;

/// 从 `bytes` 的绝对偏移读取大端 u16（越界→`STATUS_DECODE_FAILED`）。
fn u16_be(bytes: &[u8], off: usize) -> Result<u16, i32> {
    let s = bytes
        .get(off..off + 2)
        .ok_or(STATUS_DECODE_FAILED)?;
    Ok(u16::from_be_bytes([s[0], s[1]]))
}

/// 从 `bytes` 的绝对偏移读取大端 u32（越界→`STATUS_DECODE_FAILED`）。
fn u32_be(bytes: &[u8], off: usize) -> Result<u32, i32> {
    let s = bytes
        .get(off..off + 4)
        .ok_or(STATUS_DECODE_FAILED)?;
    Ok(u32::from_be_bytes([s[0], s[1], s[2], s[3]]))
}

/// `w*h > 8192*8192` 判定（u64 乘法，避免 u32 溢出）。
fn is_oversized(w: u32, h: u32) -> bool {
    u64::from(w) * u64::from(h) > MAX_PIXELS
}

/// 读取偏移 `off` 处的样本高字节（8 位样本即其自身；16 位样本 BE，高字节在前）。
/// 调用方须先保证边界（8→1B、16→2B）且 `off` 已按样本宽度步进。
fn sample_byte(data: &[u8], off: usize, depth: u16) -> u8 {
    if depth == 16 {
        // 16 位样本大端：高字节在前（与 psd-tools 垂直转换一致，取高字节即 8 位值）。
        data[off]
    } else {
        data[off]
    }
}

/// 从 PSD 字节解码为 RGBA8（行优先，每像素 R,G,B,A）。
///
/// # 返回
/// - `Ok((Vec<u8>, width, height))`：RGBA8 像素流。
/// - `Err(STATUS_UNSUPPORTED=-6)`：PSB（version=2，交 T3）/ RLE 或 ZIP 压缩 /
///   非 RGB 色彩模式 / 1036 未知格式或 planes≠1。
/// - `Err(STATUS_TOO_LARGE=-7)`：头声明或 1036 缩略图声明超 8192×8192（解码前拦截）。
/// - `Err(STATUS_DECODE_FAILED=-2)`：结构损坏 / 截断 / 魔数或版本不符 / 委托 JPEG 失败。
///
/// # 错误不变量
/// 任何输入都不会 panic；所有段长度字段均做越界校验。
#[allow(dead_code)]
// 该函数供 todo 16/17/24 或上层路由接线使用；当前 crate 为 cdylib 且
// infra/registry.rs 尚未分发解码器，仅 `#[cfg(test)]` 引用到它，故显式标注
// 以避免 dead_code 警告（同 jpeg.rs `decode_jpeg` 先例）。
pub fn decode_psd(bytes: &[u8]) -> Result<(Vec<u8>, u32, u32), i32> {
    // 预检 A：长度 / 魔数 / 版本。
    if bytes.len() < 26 {
        return Err(STATUS_DECODE_FAILED);
    }
    if &bytes[0..4] != SIG_8BPS {
        return Err(STATUS_DECODE_FAILED);
    }
    let version = u16_be(bytes, 4)?;
    if version == 2 {
        // PSB：8 字节 Layer/Mask 长度、尺寸上限不同 → 不支持，交 T3。
        return Err(STATUS_UNSUPPORTED);
    }
    if version != 1 {
        return Err(STATUS_DECODE_FAILED);
    }
    // 预检 A：channels / 位深。
    let channels = u16_be(bytes, 12)?;
    let height = u32_be(bytes, 14)?;
    let width = u32_be(bytes, 18)?;
    let depth = u16_be(bytes, 22)?;
    let color_mode = u16_be(bytes, 24)?;
    if channels == 0 {
        return Err(STATUS_DECODE_FAILED);
    }
    if depth != 8 && depth != 16 {
        return Err(STATUS_DECODE_FAILED);
    }
    // 预检 B：主图像素上限。
    if is_oversized(width, height) {
        return Err(STATUS_TOO_LARGE);
    }

    let mut pos: usize = 26;
    // 颜色模式段：4 字节大端长度 + 数据。
    let cm_len = u32_be(bytes, pos)? as usize;
    pos += 4;
    let Some(cm_end) = pos.checked_add(cm_len) else {
        return Err(STATUS_DECODE_FAILED);
    };
    if cm_end > bytes.len() {
        return Err(STATUS_DECODE_FAILED);
    }
    pos = cm_end;

    // 图像资源段：4 字节大端长度 + 8BIM 块序列。
    let res_len = u32_be(bytes, pos)? as usize;
    pos += 4;
    let Some(res_end) = pos.checked_add(res_len) else {
        return Err(STATUS_DECODE_FAILED);
    };
    if res_end > bytes.len() {
        return Err(STATUS_DECODE_FAILED);
    }
    let mut thumb_opt: Option<(usize, usize)> = None; // (data_start, data_end)
    let mut p: usize = pos;
    while p + 6 < res_end {
        if &bytes[p..p + 4] != SIG_8BIM {
            return Err(STATUS_DECODE_FAILED);
        }
        let id = u16_be(bytes, p + 4)?;
        // Pascal 名字段：1 字节长度 + 名称，整体偶对齐。
        let name_field = 1usize + bytes[p + 6] as usize;
        let name_field = if name_field % 2 == 0 { name_field } else { name_field + 1 };
        let dlen_off = p + 6 + name_field;
        let data_len = u32_be(bytes, dlen_off)? as usize;
        let data_start = dlen_off + 4;
        let Some(data_end) = data_start.checked_add(data_len) else {
            return Err(STATUS_DECODE_FAILED);
        };
        if data_end > res_end {
            return Err(STATUS_DECODE_FAILED);
        }
        if id == RES_ID_THUMBNAIL {
            thumb_opt = Some((data_start, data_end));
        }
        // 块数据偶对齐后接下一块。
        let mut next = data_end;
        if next % 2 != 0 {
            next += 1;
        }
        if next <= p {
            return Err(STATUS_DECODE_FAILED); // 前进保护，防死循环
        }
        p = next;
    }
    if let Some((ds, de)) = thumb_opt {
        return decode_thumb(&bytes[ds..de]);
    }

    // 无 1036：Layer/Mask 段（4 字节大端长度 + 数据）。
    let lm_len = u32_be(bytes, pos)? as usize;
    pos += 4;
    let Some(lm_end) = pos.checked_add(lm_len) else {
        return Err(STATUS_DECODE_FAILED);
    };
    if lm_end > bytes.len() {
        return Err(STATUS_DECODE_FAILED);
    }
    pos = lm_end;

    // ImageData 段：compression(u16 BE) + 平面序像素。
    let compression = u16_be(bytes, pos)?;
    if compression != 0 {
        // RLE(1)/ZIP(2)/ZIP_PRED(3)：简单模式不支持压缩平面 → 上层走 T2/T3。
        return Err(STATUS_UNSUPPORTED);
    }
    pos += 2;
    if color_mode != 3 {
        // 仅支持 RGB 扁平（灰阶/索引/CMYK 由 T2/T3 覆盖）。
        return Err(STATUS_UNSUPPORTED);
    }
    if channels != 3 && channels != 4 {
        return Err(STATUS_UNSUPPORTED);
    }

    let plane_len = u64::from(width)
        .checked_mul(u64::from(height))
        .and_then(|v| if depth == 16 { v.checked_mul(2) } else { Some(v) })
        .ok_or(STATUS_DECODE_FAILED)?;
    let need = plane_len
        .checked_mul(u64::from(channels))
        .ok_or(STATUS_DECODE_FAILED)?;
    if u64::try_from(bytes.len().saturating_sub(pos)).unwrap_or(0) < need {
        return Err(STATUS_DECODE_FAILED);
    }
    let plane = plane_len as usize;
    let bpc: usize = if depth == 16 { 2 } else { 1 };
    let px = u64::from(width) * u64::from(height);
    let mut out = Vec::with_capacity(px as usize * 4);
    for i in 0..px as usize {
        let o = i * bpc;
        let r = sample_byte(bytes, pos + plane * 0 + o, depth);
        let g = sample_byte(bytes, pos + plane * 1 + o, depth);
        let b = sample_byte(bytes, pos + plane * 2 + o, depth);
        let a = if channels == 4 {
            sample_byte(bytes, pos + plane * 3 + o, depth)
        } else {
            255
        };
        out.extend_from_slice(&[r, g, b, a]);
    }
    Ok((out, width, height))
}

/// 解码资源 1036 数据块（28B 头 + 负载）。
///
/// fmt=1（JPEG）：负载即完整 JPEG 文件字节，委托 `jpeg::decode_jpeg`；
/// fmt=0（RAW）：负载为交错原始像素（planes==1，bits∈{24,32}），转为 RGBA8。
fn decode_thumb(payload: &[u8]) -> Result<(Vec<u8>, u32, u32), i32> {
    if payload.len() < THUMB_HEADER_LEN {
        return Err(STATUS_DECODE_FAILED);
    }
    let fmt = u32_be(payload, 0)?;
    let tw = u32_be(payload, 4)?;
    let th = u32_be(payload, 8)?;
    let bits = u16_be(payload, 24)?;
    let planes = u16_be(payload, 26)?;
    let data = &payload[THUMB_HEADER_LEN..];
    if is_oversized(tw, th) {
        return Err(STATUS_TOO_LARGE);
    }
    match fmt {
        1 => decode_jpeg(data),
        0 => {
            // RAW：仅 planes==1（交错）且 24/32bpp 受支持；bits=16/8 或 planes>1 → -6。
            if planes != 1 || (bits != 24 && bits != 32) {
                return Err(STATUS_UNSUPPORTED);
            }
            let bpp = bits as usize / 8;
            let need = u64::from(tw) * u64::from(th) * bpp as u64;
            if (data.len() as u64) < need {
                return Err(STATUS_DECODE_FAILED);
            }
            let px = u64::from(tw) * u64::from(th);
            let mut out = Vec::with_capacity(px as usize * 4);
            for i in 0..px as usize {
                let o = i * bpp;
                let r = data[o];
                let g = data[o + 1];
                let b = data[o + 2];
                let a = if bpp == 4 { data[o + 3] } else { 255 };
                out.extend_from_slice(&[r, g, b, a]);
            }
            Ok((out, tw, th))
        }
        _ => Err(STATUS_UNSUPPORTED),
    }
}

