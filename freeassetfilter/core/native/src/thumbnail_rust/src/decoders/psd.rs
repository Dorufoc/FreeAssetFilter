    #[test]
    fn truncated_inputs_return_error_without_panic() {
        // 结构性截断点位（头内 / 资源段 / 段长度字段）必须报错且不得 panic。
        for fixture in [PSD_1036_JPEG_16X16, PSD_FLAT_RGB8_4X4, PSD_FLAT_RGB16_2X2] {
            for n in [13usize, 26, 32, fixture.len() / 2] {
                let result = decode_psd(&fixture[..n]);
                match result {
                    Err(code) => assert_ne!(code, 0, "截断 {n}B 返回值不可为 0"),
                    Ok(_) => panic!("结构性截断 {n}B 不应解码成功"),
                }
            }
        }
        // 平铺夹具：图像数据段末尾截断必须失败（JPEG 尾部截断由共享 JPEG
        // 解码器容错性决定，不作断言）。
        for fixture in [PSD_FLAT_RGB8_4X4, PSD_FLAT_RGB16_2X2] {
            let n = fixture.len().saturating_sub(5);
            let result = decode_psd(&fixture[..n]);
            match result {
                Err(code) => assert_ne!(code, 0, "平铺截断 {n}B 返回值不可为 0"),
                Ok(_) => panic!("平铺图像数据段截断 {n}B 不应解码成功"),
            }
        }
    }

