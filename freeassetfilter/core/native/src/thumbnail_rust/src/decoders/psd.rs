    /// 读取 RGBA 像素（测试辅助）。
    fn pixel(data: &[u8], w: u32, x: u32, y: u32) -> [u8; 4] {
        let i = ((y * w + x) as usize) * 4;
        [data[i], data[i + 1], data[i + 2], data[i + 3]]
    }

    /// 断言解码结果与逐像素公式一致（行优先 4x3 平面，alpha 参与比较）。
    fn assert_pixels(
        result: Result<(Vec<u8>, u32, u32), i32>,
        w: u32,
        h: u32,
        formula: impl Fn(u32, u32) -> [u8; 4],
        fixture: &str,
    ) -> (Vec<u8>, u32, u32) {
        let (data, gw, gh) = result.unwrap_or_else(|e| panic!("{fixture} 应解码成功, got Err({e})"));
        assert_eq!((gw, gh), (w, h), "{fixture} 尺寸应为 {w}x{h}");
        assert_eq!(data.len(), (w * h * 4) as usize, "{fixture} RGBA 字节数");
        for y in 0..h {
            for x in 0..w {
                assert_eq!(pixel(&data, w, x, y), formula(x, y), "{fixture} ({x},{y})");
            }
        }
        (data, gw, gh)
    }

